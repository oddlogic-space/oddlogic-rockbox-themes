#!/usr/bin/env python3
"""Rebuild the shipped In Love and Pretty Sad trees.   usage: package.py <outroot>   (writes <outroot>/inlove and <outroot>/prettysad)
build.py draws both skins under their working ids (dream, film); this script renames them to the public ids and writes the cfg and fonts.
Needs Pillow, numpy, fontTools, Noto Sans CJK Medium and Noto Serif CJK SemiBold."""
import os, re, shutil, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); COMMON = os.path.join(HERE, "..", "common")
OUTROOT = os.path.abspath(sys.argv[1])
SANS = "/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc"; SERIF = "/usr/share/fonts/opentype/noto/NotoSerifCJK-SemiBold.ttc"
HDR = """# Theme:        {name}
# Author:       Oddlogic
# Source:       https://github.com/oddlogic-space/oddlogic-rockbox-themes  (latest version, changelog, bug reports)
# Platform:     HiBy R1 (480x800 portrait touch), Rockbox hosted build (Unsupported/hosted)
# Version:      1.1
# License:      CC-BY-SA 4.0 (skins, graphics). Fonts: SIL Open Font License 1.1 (derived from Noto Sans CJK / Noto Serif CJK)
# Graphics:     All graphics generated by the author with a script (no third-party images)
# Last updated: 2026-10-14
#
"""
THEMES = [dict(id="prettysad", name="Pretty Sad", old="film", cfg="Pretty Sad.cfg", blurb="Warm paper print taped to a dark slate board."),
          dict(id="inlove", name="In Love", old="dream", cfg="In Love.cfg", blurb="Deep plum background with soft rose accents.")]
work = tempfile.mkdtemp(); env = dict(os.environ, OUT=work)
subprocess.check_call([sys.executable, f"{HERE}/build.py"], env=env)
SRC = f"{work}/.rockbox"; fonts = f"{work}/fonts"
subprocess.check_call([sys.executable, f"{COMMON}/make_fonts.py", SANS, fonts, "GirlSans", "28", "32", "40"])
subprocess.check_call([sys.executable, f"{COMMON}/make_fonts.py", SERIF, fonts, "GirlSerif", "40"])
for t in THEMES:
    i, old = t["id"], t["old"]; root = f"{OUTROOT}/{i}"; R = f"{root}/.rockbox"
    shutil.rmtree(root, ignore_errors=True)
    for d in ("fonts", "themes", "wps"): os.makedirs(f"{R}/{d}")
    for s in (28, 32, 40): shutil.copy(f"{fonts}/{s}-GirlSans.fnt", f"{R}/fonts/{s}-{i}.fnt")
    shutil.copy(f"{fonts}/40-GirlSerif.fnt", f"{R}/fonts/40-{i}serif.fnt")
    shutil.copytree(f"{SRC}/wps/{old}", f"{R}/wps/{i}")
    for ext in ("wps", "sbs"):
        s = open(f"{SRC}/wps/{old}.{ext}").read()
        s = s.replace("GirlSans.fnt", f"{i}.fnt").replace("28-GirlSans", f"28-{i}").replace("40-GirlSerif.fnt", f"40-{i}serif.fnt")
        s = re.sub(r"^# \S+ - ", f"# {t['name']} - ", s, count=1, flags=re.M).replace(" (generated by tools/build.py)", "")
        open(f"{R}/wps/{i}.{ext}", "w").write(s)
    c = open(f"{SRC}/themes/{t['cfg']}").read().split("\n")
    body = [l for l in c if l and not l.startswith("#") and not l.startswith("list separator color")]
    body = [l.replace(f"/.rockbox/wps/{old}.", f"/.rockbox/wps/{i}.").replace("32-GirlSans.fnt", f"32-{i}.fnt") for l in body]
    note = "# IMPORTANT: touch buttons need  Settings > General Settings > Display >\n#   Touchscreen Settings > Touchscreen mode > Point\n"
    open(f"{R}/themes/{i}.cfg", "w").write(HDR.format(name=t["name"]) + f"# {t['blurb']}\n" + note + "\n".join(body) + "\n")
    shutil.copy(f"{HERE}/licence/COPYING-{i}.txt", f"{R}/fonts/")
    print("built", root)
shutil.rmtree(work)
